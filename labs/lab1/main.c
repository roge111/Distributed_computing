#define _POSIX_C_SOURCE 200809L

#include <stdio.h>
#include <string.h>
#include <stdlib.h>
#include <unistd.h>

/**
 * @brief Точка входа в программу.
 *
 * Разбирает аргументы командной строки, ожидая параметр `-p`,
 * задающий количество дочерних процессов. Проверяет корректность
 * переданного значения: оно должно быть больше 1, иначе программа
 * выводит сообщение об использовании в stderr и завершается с кодом 1.
 *
 * При корректном вводе выводит общее количество процессов (включая
 * родительский) в stdout, затем с помощью `fork()` создаёт x дочерних
 * процессов. Каждый дочерний процесс печатает свой номер и выходит
 * из цикла, завершая собственную копию программы.
 *
 * @param argc Количество аргументов командной строки.
 * @param argv Массив строк аргументов командной строки; ожидается
 *             опция `-p X`, где X — количество дочерних процессов.
 *
 * @return 0 при успешном завершении; 1 в случае ошибки
 *         (неверные аргументы, количество процессов <= 1
 *         или сбой `fork()`).
 */
int main(int argc, char *argv[]) {
    int x = -1;

    int opt;
    while ((opt = getopt(argc, argv, "p:")) != -1) {
        switch (opt) {
            case 'p':
                x = atoi(optarg);
                break;
            default:
                fprintf(stderr, "Usage: %s -p X\n", argv[0]);
                return 1;
        }
    }

    if (x <= 1) {
        fprintf(stderr, "Usage: %s -p X\n", argv[0]);
        return 1;
    }

    printf("Количество процессов: %d\n", x+1);


    for (int i = 1; i < x+1; i++){
        int pid_id = fork();
        
        if (pid_id < 0) {
            perror("fork");
            return 1;
        } else if (pid_id == 0){
            printf("Дочерний процесс: %d\n", i);
            break;
        }
    }
    return 0;
}
